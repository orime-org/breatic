import { expect } from 'playwright/test';
import { test } from '../helpers/slot';
import { openSmokeProject } from '../helpers/project';
import { createSpace, deleteSpace, visibleSpace } from '../helpers/space';

test.use({ viewport: { width: 1280, height: 720 } });

test('scene floating panels preserve the approved stage, Escape and development states', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', (error) => errors.push(error.message));
  page.on('console', (message) => { if (message.type() === 'error') errors.push(message.text()); });
  await openSmokeProject(page);
  const id = await createSpace(page, '3d', `scene-layout-${Date.now()}`);
  try {
    const scene = visibleSpace(page);
    const viewport = scene.getByTestId('three-d-viewport');
    await expect(viewport).toBeVisible();
    const stage = await scene.getByTestId('scene-stage').boundingBox();
    expect(await viewport.boundingBox()).toEqual(stage);
    expect(await scene.getByTestId('scene-viewport-toolbar').getByRole('button').evaluateAll((buttons) => buttons.map((button) => button.getAttribute('aria-label')))).toEqual(['Undo', 'Redo', 'Properties', 'Objects', 'Generation tasks', 'Scene minimap']);
    await scene.getByRole('button', { name: 'Add', exact: true }).click();
    await page.getByRole('menuitem', { name: 'Add figure', exact: true }).click();
    const name = page.getByTestId('scene-properties-panel').getByLabel('Name', { exact: true });
    await expect(name).toHaveValue('Figure');
    await name.fill('  Figure  '); await name.press('Enter');
    await expect(name).toHaveValue('Figure');
    await name.fill('   '); await name.press('Tab');
    await expect(name).toHaveValue('Figure');
    await expect(name).toHaveAttribute('aria-invalid', 'false');
    const panel = page.getByTestId('scene-right-panel');
    await expect.poll(() => panel.evaluate((element) => element.getAnimations().every((animation) => animation.playState === 'finished'))).toBe(true);
    await page.screenshot({ path: test.info().outputPath('scene-properties.png'), animations: 'disabled' });
    const panelRect = await panel.boundingBox(); const mapRect = await scene.getByTestId('scene-map').boundingBox();
    if (!stage || !panelRect || !mapRect) throw new Error('The visible scene has incomplete geometry');
    expect(panelRect.x + panelRect.width).toBeCloseTo(stage.x + stage.width - 10, 1);
    expect(panelRect.y + panelRect.height).toBeLessThan(mapRect.y);
    const header = panel.getByTestId('scene-panel-header');
    const lock = header.getByTestId('scene-selection-lock');
    const close = header.getByRole('button', { name: 'Close', exact: true });
    const lockRect = await lock.boundingBox(); const closeRect = await close.boundingBox();
    if (!lockRect || !closeRect) throw new Error('The properties header has incomplete controls');
    expect(lockRect.width).toBe(32); expect(lockRect.height).toBe(32);
    expect(lockRect.y).toBe(closeRect.y);
    expect(lockRect.x + lockRect.width).toBeLessThan(closeRect.x);
    await lock.hover(); await expect(page.getByRole('tooltip')).toHaveText('Lock');
    await lock.click(); await expect(lock).toHaveAttribute('aria-pressed', 'true');
    await expect(name).toBeDisabled();
    await expect(page.getByRole('tooltip')).toHaveCount(0);
    await page.mouse.move(500, 100);
    await lock.hover(); await expect(page.getByRole('tooltip')).toHaveText('Unlock');
    await lock.click(); await expect(name).toBeEnabled();
    await name.fill('Uncommitted field draft'); await name.press('Escape');
    await expect(name).toHaveValue('Figure'); await expect(panel).toBeVisible();
    await viewport.focus(); await page.keyboard.press('Escape'); await expect(panel).toBeHidden();
    await expect(scene.getByTestId('scene-object-menu')).toBeVisible();
    await scene.getByTestId('scene-properties-trigger').click(); await expect(name).toBeVisible();
    await page.keyboard.press('Escape'); await expect(panel).toBeHidden();
    await expect(scene.getByTestId('scene-properties-trigger')).toBeFocused();
    await scene.getByTestId('scene-objects-trigger').click();
    await page.getByTestId('scene-objects-panel').getByRole('button', { name: 'Figure', exact: true }).click();
    await expect(name).toHaveValue('Figure');
    await expect(panel).toBeFocused();
    await page.keyboard.press('Tab');
    await expect(lock).toBeFocused();
    await page.keyboard.press('Space'); await expect(name).toBeDisabled();
    await page.keyboard.press('Tab'); await expect(close).toBeFocused();
    await page.keyboard.press('Shift+Tab'); await expect(lock).toBeFocused();
    await page.keyboard.press('Enter'); await expect(name).toBeEnabled();
    await scene.getByTestId('scene-objects-trigger').click();
    const figure = page.getByTestId('scene-objects-panel').getByRole('button', { name: 'Figure', exact: true });
    await figure.click({ modifiers: ['Shift'] });
    await expect(page.getByTestId('scene-objects-panel')).toBeVisible();
    await expect(figure).toBeFocused();
    await expect(scene.getByTestId('scene-object-menu')).toBeHidden();
    await figure.click(); await expect(name).toHaveValue('Figure');
    await scene.getByRole('button', { name: 'Add', exact: true }).click();
    await page.getByRole('menuitem', { name: 'Add block', exact: true }).click();
    await expect(name).toHaveValue('Stage block');
    await scene.getByTestId('scene-objects-trigger').click();
    await figure.click({ modifiers: ['Shift'] });
    await expect(page.getByTestId('scene-properties-panel')).toContainText('2 selected');
    await expect(panel).toBeFocused();
    await lock.click(); await expect(lock).toHaveAttribute('aria-pressed', 'true');
    await lock.click(); await expect(lock).toHaveAttribute('aria-pressed', 'false');
    await scene.getByTestId('scene-objects-trigger').click();
    await figure.click({ modifiers: ['Shift'] });
    await expect(name).toHaveValue('Stage block');
    await expect(panel).toBeFocused();
    await scene.getByTestId('scene-objects-trigger').click();
    const block = page.getByTestId('scene-objects-panel').getByRole('button', { name: 'Stage block', exact: true });
    await block.click({ modifiers: ['Shift'] });
    await expect(page.getByTestId('scene-objects-panel')).toBeVisible();
    await expect(block).toBeFocused();
    await expect(scene.getByTestId('scene-object-menu')).toBeHidden();
    await figure.click(); await expect(name).toHaveValue('Figure');
    await scene.getByTestId('scene-tasks-trigger').click();
    await expect(page.getByTestId('scene-tasks-panel')).toHaveText('3D model generation is in development');
    await scene.getByRole('button', { name: 'AI generation', exact: true }).click();
    const dialog = page.getByRole('dialog', { name: 'AI generation', exact: true });
    await expect(dialog).toContainText('3D model generation is in development');
    await expect(dialog.getByLabel('Describe the 3D model you want to generate')).toBeDisabled();
    await expect(dialog.getByLabel('Reference image (optional)')).toBeDisabled();
    await expect(dialog.getByRole('button', { name: 'Generate', exact: true })).toBeDisabled();
    await dialog.getByRole('button', { name: 'Cancel', exact: true }).click();
    await expect(dialog).toBeHidden();
    await expect(scene.getByTestId('scene-map').locator('canvas')).toBeVisible();
    const oldMap = await scene.getByTestId('scene-map').locator('canvas').elementHandle();
    await scene.getByRole('button', { name: 'Scene minimap', exact: true }).click();
    expect(await oldMap?.evaluate((element) => element.isConnected)).toBe(false);
    await scene.getByRole('button', { name: 'Scene minimap', exact: true }).click();
    await expect(scene.getByTestId('scene-map').locator('canvas')).toBeVisible();
    for (const theme of ['light', 'dark']) {
      await page.evaluate((value) => { document.documentElement.dataset.theme = value; }, theme);
      for (const kind of ['properties', 'objects', 'tasks']) {
        const entry = scene.getByTestId(`scene-${kind}-trigger`);
        await entry.click(); await expect(page.getByTestId(`scene-${kind}-panel`)).toBeVisible();
        await entry.click(); await expect(panel).toBeHidden();
        await entry.click(); await expect(page.getByTestId(`scene-${kind}-panel`)).toBeVisible();
        await page.mouse.move(500, 100);
        await expect(entry).toHaveCSS('background-color', 'rgba(0, 0, 0, 0)');
        await close.click(); await expect(panel).toBeHidden();
      }
      await scene.getByTestId('scene-properties-trigger').click();
      await expect(lock).toBeVisible();
      await lock.click(); await expect(lock).toHaveAttribute('aria-pressed', 'true');
      await page.mouse.move(500, 100);
      await expect(lock).toHaveCSS('background-color', 'rgba(0, 0, 0, 0)');
      expect(await lock.evaluate((element) => getComputedStyle(element).color)).toBe(await close.evaluate((element) => getComputedStyle(element).color));
      await page.screenshot({ path: test.info().outputPath(`scene-header-locked-${theme}.png`), animations: 'disabled' });
      await lock.click(); await expect(lock).toHaveAttribute('aria-pressed', 'false');
      await page.mouse.move(500, 100);
      await expect(lock).toHaveCSS('background-color', 'rgba(0, 0, 0, 0)');
      expect(await lock.evaluate((element) => getComputedStyle(element).color)).toBe(await close.evaluate((element) => getComputedStyle(element).color));
      await page.screenshot({ path: test.info().outputPath(`scene-header-unlocked-${theme}.png`), animations: 'disabled' });
      await scene.getByTestId('scene-tasks-trigger').click();
      await expect(page.getByTestId('scene-tasks-panel')).toBeVisible();
      await expect(lock).toBeHidden();
      await page.screenshot({ path: test.info().outputPath(`scene-layout-${theme}.png`), animations: 'disabled' });
      await page.keyboard.press('Escape'); await expect(panel).toBeHidden();
    }
    expect(await scene.getByTestId('scene-stage').boundingBox()).toEqual(stage);
    await test.info().attach('scene-layout-geometry', { body: JSON.stringify({ stage, panelRect, mapRect, errors }, null, 2), contentType: 'application/json' });
    expect(errors).toEqual([]);
  } finally {
    await page.screenshot({ path: test.info().outputPath('scene-last-state.png'), animations: 'disabled' });
    await deleteSpace(page, id);
  }
});
