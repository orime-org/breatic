/**
 * Filling the one address every deployment plays the voice samples from
 * (#2156, #2239). A sample already served there is left alone, so a run with
 * nothing new only asks, and a rerun makes only what a previous run could not.
 */

import { budgetDeadlineFrom } from "@breatic/core";
import type { MediaRunner } from "@breatic/provider/media";

import { MediaRunFailed, runMedia, type MediaRunDeps } from "@worker/handlers/media-run.js";
import type { VoiceSampleJob } from "@worker/voice-samples/plan.js";
import { StillRunning } from "@worker/handlers/still-running.js";

/** The key the storage check asks about. */
const PROBE_KEY = "voice-samples/probe.mp3";

/**
 * Stop before generating anything when this machine's storage settings would
 * put the samples somewhere no deployment reads them from.
 * @param storageUrl - Where the storage settings publish a key.
 * @param sampleUrl - Where every deployment plays a sample key from.
 * @throws {Error} When the two addresses differ.
 */
export function assertUploadsReachSampleAddress(
  storageUrl: (key: string) => string,
  sampleUrl: (key: string) => string,
): void {
  const stored = storageUrl(PROBE_KEY);
  const played = sampleUrl(PROBE_KEY);
  if (stored !== played) {
    throw new Error(
      `The storage settings publish ${PROBE_KEY} at ${stored}, but every deployment plays it from ${played}`,
    );
  }
}

/**
 * What a HEAD on a sample's public address says about it.
 *
 * Only a 404 means the sample is not there. Any other failure (a bucket that
 * is not public, a rate limit, an outage) leaves that unknown, and making the
 * sample again would be paid for without making it playable.
 * @param key - The sample key, for the error.
 * @param status - The HEAD's status.
 * @returns True when served, false when missing.
 * @throws {Error} When the status answers neither.
 */
export function servedFromHead(key: string, status: number): boolean {
  if (status >= 200 && status < 300) return true;
  if (status === 404) return false;
  throw new Error(`${key}: HEAD answered ${status}`);
}

/** What a sync needs from the outside. */
export interface SyncDeps {
  /** Whether the sample address already serves this key. */
  exists: (key: string) => Promise<boolean>;
  /** Run the paid prediction and answer where its output is. */
  predict: (job: VoiceSampleJob) => Promise<string>;
  /** Fetch the prediction's output. */
  download: (url: string) => Promise<Buffer>;
  /** What is done to the generated bytes before they are stored. */
  finish?: (job: VoiceSampleJob, bytes: Buffer) => Promise<Buffer>;
  /** Store the bytes under the key. */
  upload: (key: string, bytes: Buffer) => Promise<void>;
  /** Checks that what follows a prediction can run; awaited once, before the first prediction, when a sample is missing. */
  beforeMaking?: () => Promise<void>;
  /** How many passes a failing sample gets. */
  attempts: number;
  /** How many samples are made at once. */
  concurrency?: number;
}

/** What a sync did. */
export interface SyncReport {
  /** Samples the sample address already served. */
  present: number;
  /** Samples made and stored. */
  made: number;
  /** Samples still missing after every pass, with the last error. */
  failed: Array<{ key: string; error: string }>;
}

/**
 * Run each job through `work`, a few at a time.
 * @param jobs - The jobs.
 * @param concurrency - How many at once.
 * @param work - What to do with one.
 */
async function eachLimited<T>(jobs: readonly T[], concurrency: number, work: (job: T) => Promise<void>): Promise<void> {
  const queue = [...jobs];
  await Promise.all(
    Array.from({ length: Math.min(concurrency, queue.length) }, async () => {
      for (let job = queue.shift(); job !== undefined; job = queue.shift()) await work(job);
    }),
  );
}

/**
 * Make every sample the sample address does not serve yet.
 * @param jobs - Every sample the catalog names.
 * @param deps - Sample address, generator, storage and pass count.
 * @returns How many were there, made, and still missing.
 */
export async function syncVoiceSamples(jobs: readonly VoiceSampleJob[], deps: SyncDeps): Promise<SyncReport> {
  const concurrency = deps.concurrency ?? 8;
  const missing: VoiceSampleJob[] = [];
  await eachLimited(jobs, concurrency, async (job) => {
    if (!(await deps.exists(job.key))) missing.push(job);
  });
  // Kept in catalog order, whatever order the checks answered in.
  missing.sort((a, b) => jobs.indexOf(a) - jobs.indexOf(b));

  if (missing.length > 0) await deps.beforeMaking?.();

  let made = 0;
  let pending = missing;
  const errors = new Map<string, string>();
  for (let pass = 0; pass < deps.attempts && pending.length > 0; pass += 1) {
    const failedThisPass: VoiceSampleJob[] = [];
    await eachLimited(pending, concurrency, async (job) => {
      try {
        const raw = await deps.download(await deps.predict(job));
        await deps.upload(job.key, deps.finish ? await deps.finish(job, raw) : raw);
        made += 1;
        errors.delete(job.key);
      } catch (err) {
        errors.set(job.key, err instanceof Error ? err.message : String(err));
        failedThisPass.push(job);
      }
    });
    pending = failedThisPass.sort((a, b) => jobs.indexOf(a) - jobs.indexOf(b));
  }
  return {
    present: jobs.length - missing.length,
    made,
    failed: pending.map((job) => ({ key: job.key, error: errors.get(job.key) ?? "" })),
  };
}

/** How a sample waits on a run the upstream is still going with. */
export interface PredictionWaiting {
  /** How long a sample may wait from its first try before it is given up, in milliseconds. */
  budgetMs: number;
  /** How long after a running answer to ask again. */
  pollIntervalMs: number;
  /** The current time, in epoch milliseconds. */
  now: () => number;
  /** Resolve at the given time, in epoch milliseconds. */
  sleepUntil: (at: number) => Promise<void>;
}

/** A store of tickets, by sample key. */
type TicketStore = MediaRunDeps["tickets"] & {
  /**
   * Drop a sample's ticket, so its next try is planned again.
   * @param key - The sample key.
   */
  forget(key: string): void;
};

/**
 * Each sample's ticket and sending mark, kept in this process: what a canvas task keeps on its row. A ticket is
 * stored only over an older version, as the row stores it.
 * @returns The store.
 */
function ticketsInMemory(): TicketStore {
  const held = new Map<string, { ticket: { version: number } & Record<string, unknown>; sendingAt: Date | null }>();
  return {
    getProviderTicket: async (key) => held.get(key) ?? { ticket: null, sendingAt: null },
    storeTicket: async (key, ticket) => {
      const now = held.get(key);
      if (now !== undefined && now.ticket.version >= ticket.version) return false;
      held.set(key, { ticket, sendingAt: now?.sendingAt ?? null });
      return true;
    },
    markSending: async (key) => {
      const now = held.get(key);
      if (now !== undefined) now.sendingAt = new Date();
    },
    clearSending: async (key) => {
      const now = held.get(key);
      if (now !== undefined) now.sendingAt = null;
    },
    forget: (key) => {
      held.delete(key);
    },
  };
}

/** A sample has no studio, so the clone cache is never read or written. */
const NO_CLONES: MediaRunDeps["clones"] = {
  liveClonesFor: async () => [],
  recordClone: async () => false,
  retireClone: async () => undefined,
};

/**
 * A sample's run through provider, paid for once across passes (inner#1743): its ticket and sending mark are kept by
 * sample key, so a later pass recovers a send that got no answer, sends again a ticket an upstream did not take, and
 * asks again about a ticket running upstream. Within a pass, a run still going is asked about again at the time it
 * named, until the budget since the sample's first try runs out; the sample then fails this pass and keeps its
 * ticket for the next. A run provider answered failed drops its ticket, so the next pass plans a new one.
 * @param runner - The process's media runner.
 * @param waiting - The budget and the clock the waiting runs on.
 * @returns The prediction step for {@link syncVoiceSamples}.
 */
export function ticketedPredict(runner: MediaRunner, waiting: PredictionWaiting): (job: VoiceSampleJob) => Promise<string> {
  const tickets = ticketsInMemory();
  const started = new Map<string, number>();
  const deps: MediaRunDeps = {
    runner,
    tickets,
    clones: NO_CLONES,
    sourceKeyOf: async () => null,
    legacy: async () => ({}),
    readingPlace: (work) => work(),
    pollIntervalMs: waiting.pollIntervalMs,
  };
  return async (job) => {
    if (!started.has(job.key)) started.set(job.key, waiting.now());
    for (;;) {
      try {
        const done = await runMedia({
          taskId: job.key,
          studioId: null,
          model: job.model,
          input: async () => job.input,
          route: { mode: "default" },
          // A maintainer's run: each sample gets its own two hours.
          deadlineAt: budgetDeadlineFrom(Date.now()),
          outputCount: 1,
          // A failed send is not retried here.
          lastAttempt: true,
        }, deps);
        tickets.forget(job.key);
        const output = done.outputs[0];
        if (output?.kind !== "url") throw new Error(`${job.key}: the run answered no output address`);
        return output.url;
      } catch (err) {
        if (err instanceof MediaRunFailed) tickets.forget(job.key);
        if (!(err instanceof StillRunning)) throw err;
        if (waiting.now() - (started.get(job.key) ?? waiting.now()) >= waiting.budgetMs) {
          throw new Error(`${job.key}: the run was still going after ${waiting.budgetMs / 1000}s`);
        }
        await waiting.sleepUntil(err.resumeAt);
      }
    }
  };
}
